export function getSpace(id: string | undefined): Space | undefined {
  return spaces.find((space) => space.id === id)
}

export function spacesForDestination(destinationId: string): Space[] {
  return spaces.filter((space) => space.destinationId === destinationId)
}

export function spaceTypesForDestination(destinationId: string): string[] {
  return Array.from(new Set(spacesForDestination(destinationId).map((space) => space.type)))
}
